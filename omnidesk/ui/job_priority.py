"""共有スレッドプールでのジョブ優先度。

サムネイル生成・フォルダ走査・キャッシュ入出力・件数集計・ファイル操作は、
すべて ``QThreadPool.globalInstance()`` の同じ待ち行列に並ぶ。数千件のフォルダを
開くとサムネイル系のジョブがキューを埋めるため、Delete で投入したファイル操作
ジョブがその後ろで順番待ちになり、「削除してから反映されるまで数秒」の一因に
なっていた。

``QThreadPool.start(runnable, priority)`` は待ち行列からの取り出し順を優先度で
決めるので、ユーザーが結果を待っているジョブを先に走らせられる。

既知の制限: 実行中のジョブは横取りできない。したがって全スレッドがサムネイル
デコードで埋まっている瞬間は、ジョブ1本ぶん（数十ms程度）だけ待つ。数千件ぶんの
待ち行列を丸ごと待たされていた従来とは桁が違う。

``BACKGROUND`` は ``QThreadPool`` の既定優先度と同じ 0。サムネイル側の呼び出しは
優先度を明示せず既定のままにしてある（呼び出し箇所を増やさないため）。
"""

from __future__ import annotations

INTERACTIVE = 10
"""ファイル操作など、ユーザーが結果を待っているジョブ。"""

STATUS = 5
"""件数集計など、表示の更新には要るが操作をブロックしないジョブ。"""

BACKGROUND = 0
"""サムネイル生成・フォルダ走査・キャッシュ入出力。待たされてよい。"""
